//! src/ffi.rs is generated from gpu/straydog_gpu.h; this keeps the two in step.
//! STRAYDOG_UPDATE_BINDINGS=1 rewrites the file.

#[cfg(target_os = "linux")]
#[test]
fn ffi_matches_the_header() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let header = root.join("../../gpu/straydog_gpu.h");
    // A distribution libclang may come without its compiler headers (stddef.h); ROCm's clang has them.
    let rocm = std::path::PathBuf::from(std::env::var("ROCM_PATH").unwrap_or_else(|_| "/opt/rocm".into()));
    let resources = std::fs::read_dir(rocm.join("llvm/lib/clang")).into_iter().flatten().flatten();
    let includes = resources.map(|entry| format!("-isystem{}", entry.path().join("include").display()));
    let generated = bindgen::Builder::default()
        .clang_args(includes)
        .header(header.to_str().unwrap())
        .allowlist_function("sd_.*")
        .layout_tests(false)
        .raw_line("//! Generated by bindgen from gpu/straydog_gpu.h (tests/bindings.rs); do not edit.")
        .raw_line("#![allow(non_camel_case_types, clippy::missing_safety_doc)]")
        .generate()
        .expect("bindgen needs libclang")
        .to_string();
    let path = root.join("src/ffi.rs");
    if std::env::var_os("STRAYDOG_UPDATE_BINDINGS").is_some() {
        std::fs::write(&path, &generated).unwrap();
    }
    assert_eq!(std::fs::read_to_string(&path).unwrap_or_default(), generated,
               "src/ffi.rs is stale: rerun this test with STRAYDOG_UPDATE_BINDINGS=1");
}
